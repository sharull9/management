/**
 * Copies the RuneIcons glass glyphs the sidebars use into a small generated
 * module, so the client bundle carries ~25 icons instead of the package's full
 * 1.8 MB icon table. Run `pnpm icons:generate` after editing `glyphs`.
 */
import { writeFileSync } from "node:fs";
import { getIconById } from "runeicons-react";

const glyphs = [
  "glass-archive",
  "glass-archive-1",
  "glass-bookmark",
  "glass-chart-4-2",
  "glass-clipboard",
  "glass-coin-rupees-2",
  "glass-compass-square-1",
  "glass-contacts-2",
  "glass-credit-card",
  "glass-file-bend-2",
  "glass-file-text",
  "glass-folder",
  "glass-home-round-door-2",
  "glass-map-pin-2",
  "glass-mountain",
  "glass-people-3",
  "glass-people-4",
  "glass-pie-chart-2-2",
  "glass-receipt-bill",
  "glass-send",
  "glass-settings-gear-1-2",
  "glass-share-arrow-down",
  "glass-shopping-bag",
  "glass-square-check-2",
  "glass-tag",
  "glass-wallet",
] as const;

/**
 * Glass glyphs are painted with four fixed greys. Each becomes a CSS variable
 * (falling back to the original grey) so a parent can tint the glyph, e.g. the
 * active sidebar item. Presentation attributes can't read `var()`, hence `style`.
 */
const tints: Record<string, string> = {
  "#E3E3E3": "--glyph-light",
  "#E3E3E5": "--glyph-light",
  "#BBBBC0": "--glyph-mid",
  "#575757": "--glyph-shade",
  "#151515": "--glyph-deep",
};

function tintable(markup: string) {
  return markup.replace(/stop-color="(#[0-9A-Fa-f]{6})"/g, (_match, hex) => {
    const variable = tints[hex.toUpperCase()];
    if (!variable) throw new Error(`Unmapped glyph colour ${hex}`);
    return `style="stop-color:var(${variable},${hex})"`;
  });
}

const entries = glyphs.map((id) => {
  const variant = getIconById(id)?.variants.glass;
  if (!variant) throw new Error(`No glass variant for "${id}"`);
  return `  ${JSON.stringify(id)}: { viewBox: ${JSON.stringify(variant.viewBox)}, markup: ${JSON.stringify(tintable(variant.markup))} },`;
});

writeFileSync(
  new URL("../src/components/shared/rune-icons.generated.ts", import.meta.url),
  `// Generated by scripts/generate-rune-icons.ts from runeicons-react. Do not edit.
export const runeGlyphs = {
${entries.join("\n")}
} as const;

export type RuneGlyphName = keyof typeof runeGlyphs;
`,
);
console.log(`Wrote ${glyphs.length} glass glyphs.`);
